import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import {runInNewContext} from 'node:vm';
const require=createRequire(import.meta.url);
const ts=require('typescript');
const {DynamicServerError}=require('next/dist/client/components/hooks-server-context');
const source=readFileSync(new URL('../lib/catalog.ts',import.meta.url),'utf8');
const compiled=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const logs=[];
let fetchImpl;
const exports={};
runInNewContext(compiled,{exports,require,process:{env:{NEXT_PUBLIC_CATALOG_API_BASE:'http://127.0.0.1:5000'}},console:{error:(...args)=>logs.push(args)},fetch:(...args)=>fetchImpl(...args),Error});
const dynamicError=new DynamicServerError('no-store fetch');
fetchImpl=async()=>{throw dynamicError};
await assert.rejects(exports.getPublicProducts(),error=>error===dynamicError);
assert.equal(logs.length,0,'Rendering signals must not be logged as API failures');
fetchImpl=async()=>{throw new Error('Network unavailable')};
assert.equal((await exports.getPublicProducts()).connected,false);
assert.equal(logs.length,1,'Network failures must still be logged');
fetchImpl=async()=>({ok:false,status:503});
assert.equal((await exports.getPublicProducts()).connected,false);
assert.equal(logs.length,2,'HTTP failures must still be logged');
fetchImpl=async()=>({ok:true,json:async()=>({unexpected:true})});
assert.equal((await exports.getPublicProducts()).connected,false);
assert.equal(logs.length,3,'Invalid responses must still be logged');
fetchImpl=async()=>({ok:true,json:async()=>({products:[{id:'P1',slug:'P1',name:'Device',category:'Medical',inStock:true,publicPrice:null}]})});
const result=await exports.getPublicProducts();
assert.equal(result.connected,true);assert.equal(result.products.length,1);assert.equal(logs.length,3);
for(const path of ['app/page.tsx','app/products/page.tsx','app/products/[slug]/page.tsx'])assert.match(readFileSync(new URL('../'+path,import.meta.url),'utf8'),/export const dynamic = 'force-dynamic'/);
console.log('Catalog error tests passed: rendering signals rethrown silently; network/HTTP/schema failures logged; successful data preserved.');
