import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
import {join} from 'node:path';
const root=process.cwd();
const pages=['page.tsx','about/page.tsx','mission-vision/page.tsx','leadership/page.tsx','products/page.tsx','products/[slug]/page.tsx','contact/page.tsx','cart/page.tsx','quotation/success/page.tsx'];
for (const page of pages) assert.ok(existsSync(join(root,'app',page)),`Missing ${page}`);
const catalog=readFileSync(join(root,'lib/catalog.ts'),'utf8');
assert.match(catalog,/\/api\/public\/products/);
assert.doesNotMatch(catalog,/mock-backend|\/api\/products['"`]/);
const cart=readFileSync(join(root,'components/CartPageClient.tsx'),'utf8');
assert.match(cart,/Submit Quotation Request/);
assert.match(cart,/\/api\/quotations/);
const css=readFileSync(join(root,'app/globals.css'),'utf8');
for (const hex of ['#152B69','#1461C3','#CF1E2A','#E8F1FF'])assert.ok(css.includes(hex),`Missing brand color ${hex}`);
const header=readFileSync(join(root,'components/SiteHeader.tsx'),'utf8');
assert.match(header,/My Order/);
assert.doesNotMatch(header,/Cart \/ Quotation/);
const floating=readFileSync(join(root,'components/FloatingActions.tsx'),'utf8');
assert.match(floating,/cart\.open/);
assert.match(floating,/href: '\/contact'/);
assert.match(floating,/floating-count/);
const shell=readFileSync(join(root,'components/CartShell.tsx'),'utf8');
assert.match(shell,/FloatingActions/);
console.log('Source smoke checks passed: routes, public catalog guardrails, quotation submission UI wired, brand colors.');
