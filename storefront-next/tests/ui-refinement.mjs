import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const read = path => readFileSync(new URL('../' + path, import.meta.url), 'utf8');

const header = read('components/SiteHeader.tsx');
assert.match(header, /className="my-order-link"/);
assert.match(header, /createPortal/); // Mobile overlay escapes the header's stacking context.
assert.match(header, /Escape/);
assert.match(header, /aria-current/);
assert.doesNotMatch(header, /className="cart-link"/);
const footer = read('components/SiteFooter.tsx');
assert.doesNotMatch(footer, /<Image|logo-mark|logo\.png/);
const home = read('app/page.tsx');
assert.doesNotMatch(home, /Categories are website design groupings/);
assert.equal((home.match(/<EcosystemMarquee\s*\/>/g) || []).length, 1);
assert.ok(home.indexOf('<EcosystemMarquee/>') > home.indexOf('EXPLORE OUR OFFERINGS'));
assert.ok(home.indexOf('<EcosystemMarquee/>') < home.indexOf('PRODUCT DISCOVERY'));
const marquee = read('components/EcosystemMarquee.tsx');
const partners = read('lib/partners.ts');
assert.match(marquee, /partnerLogos/);
assert.match(marquee, /CONNECTED BY CARE/);
assert.match(marquee, /partner-logo-card/);
assert.match(marquee, /process\.env\.NODE_ENV === 'production'/);
assert.doesNotMatch(marquee, /Diagnostic Solutions|Hospitals & Clinics|Clinical Laboratories/);
assert.match(partners, /public\/partners\//);
const widget = read('components/FloatingActions.tsx');
assert.match(widget, /chatOpen/);
assert.match(widget, /chat-transcript/);
assert.match(widget, /chat-bubble/);
assert.match(widget, /sendQuestion/);
assert.match(widget, /Automated FAQ assistant/);
assert.match(widget, /not live chat/);
assert.match(widget, /cart\.open/);
assert.doesNotMatch(widget, /faq-question|faq-answer|chatbot.*AI/i);
const css = read('app/globals.css');
assert.match(css, /@media\(max-width:1070px\)/);
assert.match(css, /\.mobile-backdrop-dismiss/);
assert.match(css, /prefers-reduced-motion:reduce/);
assert.match(css, /\.ecosystem-track/);
assert.match(css, /\.my-order-link\{display:inline-flex/);
assert.match(css, /\.my-order-link::after\{display:none\}/);
console.log('UI regression checks passed: boxed My Order, mobile nav, footer, relocated partner carousel and conversational FAQ.');
