import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import {runInNewContext} from 'node:vm';
const require=createRequire(import.meta.url),ts=require('typescript'),exports={};
const code=ts.transpileModule(readFileSync(new URL('../src/brochure-mapping.ts',import.meta.url),'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
runInNewContext(code,{exports,Error});
const candidates=JSON.parse(readFileSync(new URL('../../docs/brochure/reviewed-candidates.json',import.meta.url),'utf8')).candidates;
const csv=readFileSync(new URL('../../docs/brochure/staff-mapping-template.csv',import.meta.url),'utf8');
const rows=exports.parseMappingCsv(csv);assert.equal(rows.length,124);assert.equal(new Set(rows.map(r=>r.candidate_id)).size,124);
const encode=rs=>{const keys=Object.keys(rows[0]);const cell=v=>'"'+String(v??'').replaceAll('"','""')+'"';return keys.map(cell).join(',')+'\r\n'+rs.map(r=>keys.map(k=>cell(r[k])).join(',')).join('\r\n');};
const chosen=rows.slice(0,2).map((r,i)=>({...r,include_in_batch:'true',staff_approved_sku:'QA-'+i,staff_review_notes:'Quoted, multiline\nreview note'}));
const draft=exports.mappingDraft(encode(chosen),candidates);
assert.equal(Object.keys(draft).length,2);assert.equal(draft[chosen[0].candidate_id].review_confirmed,false);
assert.equal(draft[chosen[0].candidate_id].model_decision,'pending');assert.match(draft[chosen[0].candidate_id].review_notes,/\n/);
assert.equal(Object.hasOwn(draft[chosen[0].candidate_id],'name'),false,'Source metadata never comes from CSV');
assert.throws(()=>exports.mappingDraft(csv,candidates),/1 to 30/);
assert.throws(()=>exports.mappingDraft(encode([...chosen,chosen[0]]),candidates),/Duplicate candidate/);
assert.throws(()=>exports.mappingDraft(encode([chosen[0],{...chosen[1],staff_approved_sku:'ｑａ-0'}]),candidates),/Duplicate SKU/);
assert.throws(()=>exports.mappingDraft(encode(rows.slice(0,31).map(r=>({...r,include_in_batch:'true'}))),candidates),/1 to 30/);
const blocked=candidates.find(c=>!c.source_ready);
assert.throws(()=>exports.mappingDraft(encode([{...chosen[0],candidate_id:blocked.candidate_id}]),candidates),/blocked/);
assert.throws(()=>exports.parseMappingCsv('a,a\n1,2'),/headers/);
assert.throws(()=>exports.parseMappingCsv('"unclosed'),/unclosed/);
console.log('Staff CSV: 124 rows, quoted/multiline data, draft-only decisions, source trust, duplicate candidate/SKU, holds and small-batch bounds passed.');
